#!/usr/bin/env python3
"""Windows IMX241 튜닝 파일(CPF/AIQB CMC)에서 libcamera IPU3 튜닝 파일(imx241.yaml) 생성."""
import struct, sys
src, dst = sys.argv[1], sys.argv[2]
d = open(src, 'rb').read()
assert d[:4] == b'CPFF' and d[0x20:0x24] == b'AIQB'
recs = {}
p, end = 0x38, 0x20 + struct.unpack_from('<I', d, 0x24)[0]
while p + 8 <= end:
    sz, fmt, key, nid = struct.unpack_from('<IBBH', d, p)
    recs.setdefault(nid, []).append(d[p + 8:p + sz]); p += sz

def cct(x, y):  # McCamy
    n = (x - 0.3320) / (0.1858 - y)
    return 449 * n**3 + 3525 * n**2 + 6823.3 * n + 5520.33

out = ['# SPDX-License-Identifier: CC0-1.0',
       '# Sony IMX241 (Samsung Galaxy Book 10.6 front camera, module START2FRONT).',
       '# Generated by gen_yaml.py from the Windows tuning file IMX241_START2FRONT_SKY.cpf',
       '# (Intel AIQB camera module characterisation): chromaticity response (AWB',
       '# locus), colour matrices and lens shading grids.',
       '%YAML 1.1', '---', 'version: 1', 'algorithms:', '  - Af:', '  - Agc:']

# AWB locus (chromaticity response, average module)
b = recs[15][0]; na, nn = struct.unpack_from('<2H', b)
pts = []
for i in range(na):
    x, y, rg, bg = struct.unpack_from('<4H', b, 4 + 8 * i)
    pts.append((cct(x / 65536, y / 65536), rg / 1024, bg / 1024))
pts.sort()
out += ['  - Awb:', '      locusTolerance: 0.06', '      locus:']
out += ['        - { ct: %d, rg: %.4f, bg: %.4f }' % (round(c), rg, bg) for c, rg, bg in pts]
# Black level: CMC 63.2-64.0 at 10 bits; ImgU OBGRID units are 2x the 10 bit
# scale (measured on the tablet with the lens covered: 128 brings dark G/B to 0).
out += ['  - BlackLevelCorrection:', '      level: 128']

# Colour matrices (Q16, preferred)
b = recs[18][0]; nm = struct.unpack_from('<H', b)[0]; mats = []
o = 2
for i in range(nm):
    ls, rg, bg, x, y = struct.unpack_from('<I4H', b, o)
    m = struct.unpack_from('<9i', b, o + 48); o += 84
    mats.append((cct(x / 65536, y / 65536), [v / 65536 for v in m]))
mats.sort()
out += ['  - Ccm:', '      ccms:']
for c, m in mats:
    out += ['        - ct: %d' % round(c), '          ccm: [ %s ]' % ', '.join('%.5f' % v for v in m)]

# Lens shading grids (Q12 gains, full native field of view, sensor order RGGB)
b = recs[10][0]; lvl, ng, gw, gh = struct.unpack_from('<4H', b); o = 8
gen = struct.unpack_from('<4H', recs[2][0]); assert gen[3] == 1  # RGGB
out += ['  - LensShadingCorrection:',
        '      bayerOrder: RGGB', '      gridSize: [ %d, %d ]' % (gw, gh),
        '      sensorSize: [ %d, %d ]' % (gen[0], gen[1]), '      scale: 4096', '      sets:']
names = ['r', 'gr', 'gb', 'b']
for i in range(ng):
    st, cl, x, y = struct.unpack_from('<4H', b, o); o += 8
    g = struct.unpack_from('<%dH' % (4 * gw * gh), b, o); o += 8 * gw * gh
    out += ['        - ct: %d' % round(cct(x / 65536, y / 65536))]
    for k in range(4):
        ch = g[k * gw * gh:(k + 1) * gw * gh]
        out += ['          %s: [ %s ]' % (names[k], ', '.join(str(v) for v in ch))]
out += ['  - ToneMapping:', '      srgb: true', '...', '']
open(dst, 'w').write('\n'.join(out))
print('locus', [(round(c), rg, bg) for c, rg, bg in pts])
print('ccm cts', [round(c) for c, _ in mats])
